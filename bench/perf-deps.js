'use strict';

/**
 * Scaling benchmark for the `deps` producer's whole-manifest path.
 *
 * `euthyna audit` queries EVERY dependency the manifest names (the `--all`
 * shape). The per-dep resolvers re-scan the manifest text for each dependency —
 * `resolveNpm` iterates every `packages` key per dep, `resolveCargo` splits the
 * whole file per dep, and each evidence line lookup walks the text prefix — so
 * the whole-manifest cost may grow faster than the manifest itself. This script
 * measures exactly that shape at increasing sizes, so a change to indexing has
 * a baseline to be judged against, and a reader can see at a glance whether the
 * per-dependency cost is flat or compounding.
 *
 * The manifests are synthetic but shape-real: npm v3 with scoped and unscoped
 * names, Cargo.lock with [[package]] blocks. Absolute numbers are
 * machine-dependent; the per-dependency ratio is the number that matters.
 *
 *   node bench/perf-deps.js [--npm-sizes 500,1000,2000,4000] [--cargo-sizes 500,1000,2000]
 *
 * 索引化之前实测（本机）：npm 每依赖 0.46 → 0.92 → 1.81 → 3.75 ms（清单每翻倍
 * 翻一倍，O(n²) 形状），cargo 0.27 → 0.91 ms/依赖 同形。
 * 索引化之后实测（同机）：npm 0.04 → 0.09 ms/依赖，cargo 恒定 ~0.05 —— 4000 依赖
 * 从 15.0s 降到 0.36s。npm 残留的轻微超线性来自每个命中一次的原生 indexOf 证据
 * 锚定（O(文件) 但字节速度），绝对值已不构成实际天花板。
 */

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i === -1 ? fallback : args[i + 1];
};
const parseSizes = (raw) =>
  String(raw)
    .split(',')
    .map(Number);
const NPM_SIZES = parseSizes(opt('--npm-sizes', '500,1000,2000,4000'));
const CARGO_SIZES = parseSizes(opt('--cargo-sizes', '500,1000,2000'));

function npmLockfile(n) {
  const packages = {
    '': { name: 'fixture', version: '1.0.0', dependencies: {} }
  };
  for (let i = 0; i < n; i++) {
    // Scoped names every seventh package: resolveNpm must handle both, and the
    // nested-scope key form is what makes its split-by-node_modules non-trivial.
    const name = i % 7 === 0 ? `@scope/pkg-${i}` : `pkg-${i}`;
    packages[`node_modules/${name}`] = {
      version: `${(i % 20) + 1}.${i % 9}.${i % 5}`,
      resolved: `https://registry.example/${name}/-/${name}.tgz`,
      integrity: `sha512-${'a'.repeat(40)}`
    };
  }
  return JSON.stringify({ name: 'fixture', lockfileVersion: 3, packages }, null, 2);
}

function cargoLockfile(n) {
  let text = '# This file is automatically @generated by Cargo.\nversion = 3\n\n';
  for (let i = 0; i < n; i++) {
    text += `[[package]]\nname = "crate-${i}"\nversion = "1.${i % 10}.${i % 7}"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "${'b'.repeat(40)}"\n\n`;
  }
  return text;
}

async function measure(label, file, type, text, size) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'euthyna-deps-perf-'));
  fs.writeFileSync(path.join(dir, file), text);
  try {
    const { listDependencies, collectDependencyFacts } = await import('../src/facts/deps.js');
    const names = listDependencies(type, text);
    const start = process.hrtime.bigint();
    const { measured } = await collectDependencyFacts({ cwd: dir, deps: names });
    const ms = Number(process.hrtime.bigint() - start) / 1e6;
    if (!measured) throw new Error(`${label} ${size}: the producer could not measure its own fixture`);
    process.stdout.write(
      `  ${String(size).padStart(6)} 依赖  ${ms.toFixed(0).padStart(7)} ms  (${(ms / size).toFixed(2)} ms/依赖, 清单 ${(text.length / 1024 / 1024).toFixed(1)} MB)\n`
    );
    return ms / size;
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

async function main() {
  if (!NPM_SIZES.every(Number.isFinite) || !CARGO_SIZES.every(Number.isFinite)) {
    throw new Error('--npm-sizes/--cargo-sizes 必须是逗号分隔的整数');
  }

  const results = [];
  for (const size of NPM_SIZES) {
    const ratio = await measure('npm', 'package-lock.json', 'npm', npmLockfile(size), size);
    results.push({ kind: 'npm', size, ratio });
  }
  for (const size of CARGO_SIZES) {
    const ratio = await measure('cargo', 'Cargo.lock', 'cargo', cargoLockfile(size), size);
    results.push({ kind: 'cargo', size, ratio });
  }

  for (const kind of ['npm', 'cargo']) {
    const rows = results.filter((r) => r.kind === kind);
    if (rows.length < 2) continue;
    const spread = Math.max(...rows.map((r) => r.ratio)) / Math.min(...rows.map((r) => r.ratio));
    const first = rows[0];
    const last = rows[rows.length - 1];
    console.log(`\n结论 (${kind}):`);
    if (last.ratio > first.ratio * 2) {
      console.log(
        '  每依赖成本在随清单变大 —— 超线性。若绝对值回到秒级，' +
          '先查每依赖是否又在重扫全文（name→条目索引是否还在），' +
          '以及证据行锚定的 indexOf 是否回到了逐字符的前缀遍历。'
      );
    } else if (last.ratio < first.ratio * 0.5) {
      console.log('  每依赖成本在变小 —— 次线性，固定开销在小规模档位里占比较高。');
    } else {
      console.log('  每依赖成本基本恒定 —— 线性缩放，当前形状没有明显天花板。');
    }
  }
  console.log('  绝对数值依赖机器；横向比较 ms/依赖 而非 ms。');
}

main().catch((error) => {
  console.error(`bench/perf-deps.js: ${error.message}`);
  process.exitCode = 1;
});
